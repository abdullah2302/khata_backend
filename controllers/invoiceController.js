import Client from '../models/Client.js';
import Project from '../models/Project.js';
import Invoice from '../models/Invoice.js';
import asyncHandler from '../utils/asyncHandler.js';
import httpError from '../utils/httpError.js';
import assertOwned from '../utils/assertOwned.js';
import syncOverdue from '../utils/syncOverdue.js';
import nextInvoiceNumber from '../utils/nextInvoiceNumber.js';
import { assertWithinBudget } from '../utils/projectFinance.js';
import { startOfToday } from '../utils/dates.js';
import { paginate, searchFilter, exactFilters, dateRange } from '../utils/query.js';

const listPopulate = [
  { path: 'client', select: 'name' },
  { path: 'project', select: 'title' }
];
const detailPopulate = [
  { path: 'client', select: 'name company email phone' },
  { path: 'project', select: 'title description' }
];

const findOwned = async (req) => {
  const invoice = await Invoice.findOne({ _id: req.params.id, owner: req.user._id });
  if (!invoice) throw httpError(404, 'Invoice not found');
  return invoice;
};

// Validates the client and project on the request and returns the project (or null).
// The project must belong to the user AND to the same client as the invoice.
const loadProject = async (req) => {
  const { client, project: projectId } = req.body;
  await assertOwned(Client, client, req.user._id, 'client');
  if (!projectId) return null;
  const project = await Project.findOne({ _id: projectId, owner: req.user._id });
  if (!project) throw httpError(400, 'Invalid project');
  if (String(project.client) !== String(client)) throw httpError(400, 'That project belongs to a different client');
  return project;
};

// pending past its due date is overdue, overdue with a future due date is pending
const normalizeStatus = (invoice) => {
  const today = startOfToday();
  if (invoice.status === 'pending' && invoice.dueDate < today) invoice.status = 'overdue';
  else if (invoice.status === 'overdue' && invoice.dueDate >= today) invoice.status = 'pending';
};

// GET /api/invoices?status=pending&client=<id>&search=INV&from=2026-11-01&to=2026-12-31&sort=-amount
export const getInvoices = asyncHandler(async (req, res) => {
  await syncOverdue(req.user._id);
  const filter = {
    owner: req.user._id,
    ...exactFilters(req.query, ['status', 'client', 'project']),
    ...searchFilter(req.query.search, ['invoiceNumber']),
    ...dateRange('dueDate', req.query.from, req.query.to)
  };
  res.json(await paginate(Invoice, filter, req.query, listPopulate));
});

export const getInvoice = asyncHandler(async (req, res) => {
  await syncOverdue(req.user._id);
  const invoice = await findOwned(req);
  res.json(await invoice.populate(detailPopulate));
});

// POST /api/invoices  -> invoiceNumber is generated by the server
export const createInvoice = asyncHandler(async (req, res) => {
  const project = await loadProject(req);
  await assertWithinBudget(req.user._id, project, req.body.amount);
  const invoiceNumber = await nextInvoiceNumber(req.user._id);
  const invoice = new Invoice({ ...req.body, invoiceNumber, owner: req.user._id });
  normalizeStatus(invoice);
  await invoice.save();
  res.status(201).json(invoice);
});

// PUT /api/invoices/:id  -> the invoice number never changes after creation
export const updateInvoice = asyncHandler(async (req, res) => {
  const invoice = await findOwned(req);
  const project = await loadProject(req);
  await assertWithinBudget(req.user._id, project, req.body.amount, invoice._id); // ignore this invoice's old amount
  Object.assign(invoice, req.body);
  if (!req.body.project) invoice.project = undefined;
  normalizeStatus(invoice);
  await invoice.save();
  res.json(invoice);
});

// PATCH /api/invoices/:id/paid
export const markInvoicePaid = asyncHandler(async (req, res) => {
  const invoice = await findOwned(req);
  invoice.status = 'paid';
  await invoice.save();
  res.json(invoice);
});

// POST /api/invoices/:id/duplicate -> same client, project and amount, new number, due in 30 days
export const duplicateInvoice = asyncHandler(async (req, res) => {
  const source = await findOwned(req);
  const project = source.project ? await Project.findOne({ _id: source.project, owner: req.user._id }) : null;
  await assertWithinBudget(req.user._id, project, source.amount);

  const dueDate = new Date();
  dueDate.setDate(dueDate.getDate() + 30);
  const copy = await Invoice.create({
    owner: req.user._id,
    client: source.client,
    project: source.project,
    amount: source.amount,
    status: 'pending',
    dueDate,
    invoiceNumber: await nextInvoiceNumber(req.user._id)
  });
  res.status(201).json(copy);
});

export const deleteInvoice = asyncHandler(async (req, res) => {
  const invoice = await findOwned(req);
  await invoice.deleteOne();
  res.json({ message: 'Invoice deleted' });
});
